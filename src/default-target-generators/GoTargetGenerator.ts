    public renderListenerFile = (listenerFile: OutputModelObjects.ListenerFile, declaration: boolean,
        options: IGenerationOptions): string => {
        this.invariants.grammarName = listenerFile.grammarName;
        this.invariants.grammarFileName = listenerFile.grammarFileName;
        this.invariants.packageName = this.packageName(options);

        const grammarName = listenerFile.grammarName;
        const result: Lines = this.renderFileHeader(listenerFile);

        result.push(
            ``,
            `package ${this.invariants.packageName} // ${grammarName}`,
            ``,
            `import "github.com/antlr4-go/antlr/v4"`,
            ``,
            `// ${grammarName}Listener is a complete listener for a parse tree produced by ${listenerFile.parserName}.`,
            `type ${grammarName}Listener interface {`,
            `\tantlr.ParseTreeListener`,
            ``,
        );

        const names = Array.from(listenerFile.listenerNames);
        names.forEach((lname, index) => {
            const name = this.toTitleCase(lname);
            result.push(
                `\t// Enter${name} is called when entering the ${lname} production.`,
                `\tEnter${name}(c *${name}Context)`,
            );

            if (index < names.length - 1) {
                result.push(``);
            }
        });

        result.push(``);

        names.forEach((lname, index) => {
            const name = this.toTitleCase(lname);
            result.push(
                `\t// Exit${name} is called when exiting the ${lname} production.`,
                `\tExit${name}(c *${name}Context)`,
            );

            if (index < names.length - 1) {
                result.push(``);
            }
        });

        result.push(`}`);

        return this.finish(result);
    };

