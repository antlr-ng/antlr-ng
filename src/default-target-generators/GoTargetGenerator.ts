    public renderTestFile = (grammarName: string, lexerName: string, parserName: string | undefined,
        parserStartRuleName: string | undefined, showDiagnosticErrors: boolean, traceATN: boolean, profile: boolean,
        showDFA: boolean, useListener: boolean, useVisitor: boolean, predictionMode: string, buildParseTree: boolean,
    ): string => {
        const result: Lines = [];

        result.push(
            `package main`,
            ``,
            `import (`,
            `\t"fmt"`,
            `\t"os"`,
            ``,
            `\t"github.com/antlr4-go/antlr/v4"`,
            `\t"test/parser"`,
            `)`,
        );

        if (parserName !== undefined) {
            result.push(
                ``,
                `import "reflect"`,
                ``,
                `type TreeShapeListener struct {`,
                `\t*parser.Base${grammarName}Listener`,
                `}`,
                ``,
                `func NewTreeShapeListener() *TreeShapeListener {`,
                `\treturn new(TreeShapeListener)`,
                `}`,
                ``,
                `func (this *TreeShapeListener) EnterEveryRule(ctx antlr.ParserRuleContext) {`,
                `\tfor i := 0; i < ctx.GetChildCount(); i++ {`,
                `\t\tchild := ctx.GetChild(i)`,
                `\t\tparentR, ok := child.GetParent().(antlr.ParserRuleContext)`,
                ``,
                `\t\t// Have to use reflect here - we need to compare the underlying pointers, but we`,
                `\t\t// do not know the types of the underlying structs, just that they will be the same`,
                `\t\t// type.`,
                `\t\tparPointer := reflect.ValueOf(parentR).Elem().Addr().Pointer()`,
                `\t\tctxPointer := reflect.ValueOf(ctx).Elem().Addr().Pointer()`,
                `\t\tif !ok || parPointer != ctxPointer {`,
                `\t\t\tpanic("Invalid parse tree shape detected.")`,
                `\t\t}`,
                `\t}`,
                `}`,
            );
        }

        result.push(
            ``,
            `func main() {`,
        );

        if (traceATN) {
            result.push(`\tantlr.ParserATNSimulatorTraceATNSim = true`);
        }

        result.push(
            `\tinput, err := antlr.NewFileStream(os.Args[1])`,
            `\tif err != nil {`,
            `\t\tfmt.Printf("Failed to find file: %v", err)`,
            `\t\treturn`,
            `\t}`,
            `\tlexer := parser.New${lexerName}(input)`,
            `\tstream := antlr.NewCommonTokenStream(lexer, 0)`,
        );

        if (parserName !== undefined) {
            result.push(
                `\tp := parser.New${parserName}(stream)`,
                `\tp.Interpreter.SetPredictionMode(antlr.PredictionMode${predictionMode})`,
            );

            if (!buildParseTree) {
                result.push(`\tp.BuildParseTrees = false`);
            }

            if (showDiagnosticErrors) {
                result.push(`\tp.AddErrorListener(antlr.NewDiagnosticErrorListener(true))`);
            }

            result.push(
                `\ttree := p.${this.toTitleCase(parserStartRuleName ?? "")}()`,
                `\tantlr.ParseTreeWalkerDefault.Walk(NewTreeShapeListener(), tree)`,
            );
        } else {
            result.push(
                `\tstream.Fill()`,
                `\tfor _, t := range stream.GetAllTokens() {`,
                `\t\tfmt.Println(t)`,
                `\t}`,
            );

            if (showDFA) {
                result.push(
                    `\tfmt.Print(lexer.GetInterpreter().DecisionToDFA()[antlr.LexerDefaultMode].ToLexerString())`,
                );
            }
        }

        result.push(`}`);

        return this.finish(result);
    };

