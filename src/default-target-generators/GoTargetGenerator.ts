    public renderParserFile = (parserFile: OutputModelObjects.ParserFile, declaration: boolean,
        options: IGenerationOptions): string => {
        const parser = parserFile.parser;
        this.invariants.recognizerName = parser.name;
        this.invariants.grammarName = parser.grammarName;
        this.invariants.grammarFileName = parser.grammarFileName;
        this.invariants.tokenLabelType = this.goType(parserFile.TokenLabelType ?? "antlr.Token");
        this.invariants.packageName = this.packageName(options);
        this.invariants.isLexer = false;
        this.invariants.contextSuperClass = parserFile.contextSuperClass
            ? this.renderActionChunks([parserFile.contextSuperClass]).join("") : undefined;

        const namedActions = parserFile.namedActions;
        const result: Lines = this.renderFileHeader(parserFile);

        result.push(
            ``,
            `package ${this.invariants.packageName} // ${parser.grammarName}`,
            ``,
            `import (`,
            `\t"fmt"`,
            `\t"strconv"`,
            `\t"sync"`,
            ``,
        );

        const includes = namedActions.get("includes");
        if (includes) {
            result.push(
                `\t// Grammar author supplied additional includes`,
                ...this.indent(this.renderAction(includes)),
            );
        }

        result.push(
            `\t"github.com/antlr4-go/antlr/v4"`,
            `)`,
        );

        const header = namedActions.get("header");
        if (header) {
            result.push(``, ...this.renderAction(header));
        }

        result.push(
            ``,
            `// Suppress unused import errors`,
            `var _ = fmt.Printf`,
            `var _ = strconv.Itoa`,
            `var _ = sync.Once{}`,
            ``,
        );
        this.append(result, this.renderParser(parser, namedActions));

        return this.finish(result);
    };

