    protected override renderStructDecl = (struct: OutputModelObjects.StructDecl): Lines => {
        const result = this.startRendering("StructDecl");

        const name = struct.escapedName;
        const parserName = this.invariants.recognizerName;
        const contextSuperClass = this.invariants.contextSuperClass;

        // The interface for the context.
        result.push(
            `// I${name} is an interface to support dynamic dispatch.`,
            `type I${name} interface {`,
            `\tantlr.ParserRuleContext`,
            ``,
            `\t// GetParser returns the parser.`,
            `\tGetParser() antlr.Parser`,
        );

        const accessors = this.renderAccessorSignatures(struct);
        if (accessors.length > 0) {
            result.push(``, ...this.indent(accessors));
        }

        if (struct.signatures.size > 0) {
            result.push(
                ``,
                `\t// Getter signatures`,
                ...this.indent(this.renderDecls(struct.signatures)),
            );
        }

        result.push(
            ``,
            `\t// Is${name} differentiates from other interfaces.`,
            `\tIs${name}()`,
            `}`,
            ``,
        );

        // The context struct.
        result.push(
            `type ${name} struct {`,
            `\t${contextSuperClass ? `*${contextSuperClass}` : "antlr.BaseParserRuleContext"}`,
            `\tparser antlr.Parser`,
            ...this.indent(this.renderDecls(struct.attrs)),
            `}`,
            ``,
        );

        const initBase = contextSuperClass
            ? `p.${contextSuperClass} = New${contextSuperClass}(nil, -1)`
            : `antlr.InitBaseParserRuleContext(&p.BaseParserRuleContext, nil, -1)`;

        result.push(
            `func NewEmpty${name}() *${name} {`,
            `\tvar p = new(${name})`,
            `\t${initBase}`,
            `\tp.RuleIndex = ${parserName}RULE_${struct.derivedFromName}`,
            `\treturn p`,
            `}`,
            ``,
            `func InitEmpty${name}(p *${name}) {`,
            `\t${initBase}`,
            `\tp.RuleIndex = ${parserName}RULE_${struct.derivedFromName}`,
            `}`,
            ``,
            `func (*${name}) Is${name}() {}`,
            ``,
        );

        const ctorArgs = struct.ctorAttrs.map((a) => {
            return `, ${a.escapedName} ${this.goType(a.type)}`;
        }).join("");

        result.push(
            `func New${name}(parser antlr.Parser, parent antlr.ParserRuleContext, invokingState int${ctorArgs}) ` +
            `*${name} {`,
            `\tvar p = new(${name})`,
            ``,
            contextSuperClass
                ? `\tp.${contextSuperClass} = New${contextSuperClass}(parent, invokingState)`
                : `\tantlr.InitBaseParserRuleContext(&p.BaseParserRuleContext, parent, invokingState)`,
            ``,
            `\tp.parser = parser`,
            `\tp.RuleIndex = ${parserName}RULE_${struct.derivedFromName}`,
            ``,
        );

        if (struct.ctorAttrs.length > 0) {
            for (const a of struct.ctorAttrs) {
                result.push(`\tp.${a.escapedName} = ${a.escapedName}`);
            }
            result.push(``);
        }

        result.push(
            `\treturn p`,
            `}`,
            ``,
            `func (s *${name}) GetParser() antlr.Parser { return s.parser }`,
            ``,
        );

        result.push(...this.renderAccessorMethods(struct));
        result.push(...this.renderGetters(struct));

        // Don't need copy unless we have subclasses.
        if (struct.provideCopyFrom) {
            result.push(
                `func (s *${name}) CopyAll(ctx *${name}) {`,
                `\ts.CopyFrom(&ctx.BaseParserRuleContext)`,
            );

            for (const a of struct.attrs) {
                result.push(`\ts.${a.escapedName} = ctx.${a.escapedName}`);
            }

            result.push(
                `}`,
                ``,
            );
        }

        result.push(
            `func (s *${name}) GetRuleContext() antlr.RuleContext {`,
            `\treturn s`,
            `}`,
            ``,
            `func (s *${name}) ToStringTree(ruleNames []string, recog antlr.Recognizer) string {`,
            `\treturn antlr.TreesStringTree(s, ruleNames, recog)`,
            `}`,
            ``,
            ...this.renderDispatchMethods(struct),
        );

        for (const e of struct.extensionMembers) {
            result.push(...this.renderAction(e as OutputModelObjects.Action), ``);
        }

        return this.endRendering("StructDecl", result);
    };

